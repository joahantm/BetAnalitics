@st.cache_data(ttl=1800)
def obtener_datos_liga(codigo_liga):
    if not FOOTBALL_API_KEY or FOOTBALL_API_KEY == "TU_API_KEY_FOOTBALL_DATA":
        return pd.DataFrame(), pd.DataFrame(), {}, "Falta configurar FOOTBALL_API_KEY."

